#!/bin/bash
set -e

cd /docker/host-myadmin

NETWORK=dbmanage-network
# Must match container_name in docker-compose.yml
SELF=host-phpmyadmin

# Own statement so a docker failure stops the script here instead of looking like an empty network
CONTAINERS=$(docker network inspect "$NETWORK" --format '{{range .Containers}}{{.Name}}{{"\n"}}{{end}}')

# Every container on the network except phpMyAdmin itself is a DB host.
# Sorted (same order under cron and a login shell) so an unchanged list doesn't recreate the container.
PMA_HOSTS=$(echo "$CONTAINERS" \
  | { grep -v -x -e "$SELF" -e '' || true; } | LC_ALL=C sort | paste -sd, -)

if [ -z "$PMA_HOSTS" ]; then
  echo "No DB containers found on $NETWORK; leaving phpMyAdmin as is." >&2
  exit 1
fi

# Compose auto-loads .env, so plain `docker compose` commands keep working between runs
printf '# Generated by update-container.sh, overwritten on every run\nPMA_HOSTS=%s\n' "$PMA_HOSTS" > .env

# No `down` first: `up -d` recreates the container only when the image or config changed
echo "Updating the phpMyAdmin container..."
docker compose up -d --pull always --quiet-pull

echo "Update complete!"
